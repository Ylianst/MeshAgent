// Package the Agent-owned Shell source as data for the Agent installer.
// No GNOME code is executed by requiring the generated CommonJS module.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {deflateSync} from 'node:zlib';

const uuid = 'meshagent-console@meshcentral.com';
const sourceDirectory = new URL('./' + uuid + '/', import.meta.url);
const output = new URL('../../modules/linux-gnome-companion-assets.js', import.meta.url);
const embeddedOutput = new URL('../../microscript/ILibDuktape_Polyfills.c', import.meta.url);
const names = ['metadata.json', 'protocol.js', 'extension.js'];

export function renderBundle() {
    const files = {};
    for (const name of names) {
        const source = new URL(name, sourceDirectory);
        if (!fs.lstatSync(source).isFile())
            throw new Error('Companion source must be a regular file: ' + name);
        const data = fs.readFileSync(source);
        if (!data.length || data.length > 1024 * 1024)
            throw new Error('Unexpected companion source size: ' + name);
        files[name] = {
            encoding: 'base64',
            bytes: data.length,
            sha256: createHash('sha256').update(data).digest('hex'),
            data: data.toString('base64'),
        };
    }
    const metadata = JSON.parse(Buffer.from(files['metadata.json'].data, 'base64'));
    if (metadata.uuid !== uuid || !Number.isInteger(metadata.version) ||
        metadata.version < 1 || metadata.version > 0xffffffff ||
        !Array.isArray(metadata['shell-version']) || !metadata['shell-version'].length ||
        !Array.isArray(metadata['session-modes']) ||
        !['user', 'unlock-dialog', 'gdm'].every(mode => metadata['session-modes'].includes(mode)))
        throw new Error('Companion metadata does not match the Agent bridge');
    return '// Generated by addons/gnome-shell/generate-assets.mjs. Do not edit.\n' +
        '// Data only; the extension executes inside GNOME Shell.\n' +
        'module.exports = ' + JSON.stringify({uuid, version: metadata.version, files}, null, 4) + ';\n';
}

export function renderEmbedding(source, rendered = renderBundle()) {
    const name = 'linux-gnome-companion-assets';
    const compressed = deflateSync(Buffer.from(rendered)).toString('base64');
    const statement = 'duk_peval_string_noresult(ctx, "addCompressedModule(\'' + name +
        '\', Buffer.from(\'' + compressed + '\', \'base64\'), \'2026-11-07T00:00:00.000Z\');");';
    const existing = /^[ \t]*duk_peval_string_noresult\(ctx, "addCompressedModule\('linux-gnome-companion-assets',[^\r\n]*$/gm;
    const matches = [...source.matchAll(existing)];
    if (matches.length > 1)
        throw new Error('Duplicate GNOME companion embedded modules');
    if (matches.length)
        return source.replace(existing, '\t' + statement);
    const anchor = /^[ \t]*duk_peval_string_noresult\(ctx, "addCompressedModule\('linux-gnome-helpers',[^\r\n]*$/gm;
    if ([...source.matchAll(anchor)].length !== 1)
        throw new Error('Cannot locate the existing GNOME module embedding');
    const newline = source.includes('\r\n') ? '\r\n' : '\n';
    return source.replace(anchor, line => '\t' + statement + newline + line);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check'))
        throw new Error('Usage: node addons/gnome-shell/generate-assets.mjs [--check]');
    const rendered = renderBundle();
    const originalEmbedding = fs.readFileSync(embeddedOutput, 'utf8');
    const renderedEmbedding = renderEmbedding(originalEmbedding, rendered);
    if (process.argv[2] === '--check') {
        if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== rendered)
            throw new Error('GNOME companion bundle is stale; run the generator');
        if (originalEmbedding !== renderedEmbedding)
            throw new Error('Embedded GNOME companion bundle is stale; run the generator');
        console.log('GNOME companion module and embedded bundle match their source');
    } else {
        fs.writeFileSync(output, rendered);
        fs.writeFileSync(embeddedOutput, renderedEmbedding);
        console.log('Generated the Agent-owned GNOME companion asset module');
    }
}
